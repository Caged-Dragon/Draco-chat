create or replace function private.guard_group_message_update()
returns trigger language plpgsql set search_path = '' as $$
begin
  if auth.uid() is null then return new; end if;
  if new.group_id is distinct from old.group_id or new.sender_id is distinct from old.sender_id
     or new.created_at is distinct from old.created_at then
    raise exception 'Group message ownership is immutable';
  end if;
  if auth.uid() <> old.sender_id then
    if (new.content, new.attachment_url, new.attachment_type, new.attachment_name,
        new.reply_to_id, new.edited_at, new.deleted_at, new.expires_at, new.mentions)
       is distinct from
       (old.content, old.attachment_url, old.attachment_type, old.attachment_name,
        old.reply_to_id, old.edited_at, old.deleted_at, old.expires_at, old.mentions) then
      raise exception 'Only the sender can edit this message';
    end if;
  end if;
  return new;
end; $$;
drop trigger if exists guard_group_message_update on public.group_messages;
create trigger guard_group_message_update before update on public.group_messages
  for each row execute function private.guard_group_message_update();

