create or replace function private.guard_message_update()
returns trigger language plpgsql set search_path = '' as $$
begin
  if auth.uid() is null then return new; end if;
  if new.sender_id is distinct from old.sender_id or new.receiver_id is distinct from old.receiver_id
     or new.created_at is distinct from old.created_at then
    raise exception 'Message participants and timestamp are immutable';
  end if;
  if auth.uid() <> old.sender_id then
    if (new.content, new.attachment_url, new.attachment_type, new.attachment_name,
        new.reply_to_id, new.edited_at, new.deleted_at, new.expires_at)
       is distinct from
       (old.content, old.attachment_url, old.attachment_type, old.attachment_name,
        old.reply_to_id, old.edited_at, old.deleted_at, old.expires_at) then
      raise exception 'Receivers can only mark messages read or pin them';
    end if;
  end if;
  return new;
end; $$;
drop trigger if exists guard_message_update on public.messages;
create trigger guard_message_update before update on public.messages
  for each row execute function private.guard_message_update();

