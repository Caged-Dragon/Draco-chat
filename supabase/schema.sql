-- 1) PROFILES
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  email text not null,
  created_at timestamptz default now(),
  avatar_url text,
  status_message text,
  presence_status text not null default 'online'
    check (presence_status in ('online','away','busy','dnd','offline')),
  last_seen_at timestamptz default now(),
  user_number bigint generated by default as identity unique,
  constraint profiles_username_format check (username ~ '^[A-Za-z0-9_]{3,20}$'),
  constraint profiles_status_message_len check (status_message is null or char_length(status_message) <= 500)
);
alter table public.profiles enable row level security;

drop policy if exists "Profiles are viewable by authenticated users" on public.profiles;
create policy "Profiles are viewable by authenticated users" on public.profiles
  for select to authenticated using (true);
drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

-- Email addresses are private: other users can never read the email column.
-- (The app reads its own email from the auth session: user.email.)
revoke select on public.profiles from anon, authenticated;
grant select (id, username, created_at, avatar_url, status_message, presence_status, last_seen_at, user_number)
  on public.profiles to authenticated;
revoke all on all tables in schema public from anon;
-- Users may edit only these columns of their own profile row
grant update (username, avatar_url, status_message, presence_status, last_seen_at)
  on public.profiles to authenticated;

create or replace function public.lock_user_number()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.user_number := old.user_number;
  new.id := old.id;
  new.created_at := old.created_at;
  return new;
end; $$;
drop trigger if exists lock_user_number_on_update on public.profiles;
create trigger lock_user_number_on_update before update on public.profiles
  for each row execute function public.lock_user_number();

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  base_username text;
  final_username text;
  attempts int := 0;
begin
  base_username := left(regexp_replace(coalesce(
    new.raw_user_meta_data->>'username',
    new.raw_user_meta_data->>'user_name',
    new.raw_user_meta_data->>'full_name',
    split_part(coalesce(new.email, ''), '@', 1),
    ''
  ), '[^a-zA-Z0-9_]', '', 'g'), 20);
  if base_username is null or base_username = '' then
    base_username := 'user';
  elsif char_length(base_username) < 3 then
    base_username := 'user' || base_username;
  end if;
  final_username := base_username;
  loop
    begin
      insert into public.profiles (id, username, email)
      values (new.id, final_username, coalesce(new.email, ''));
      exit;
    exception when unique_violation then
      attempts := attempts + 1;
      if attempts > 20 then
        final_username := 'user' || substr(replace(new.id::text, '-', ''), 1, 12);
      else
        final_username := left(base_username, 15) || floor(random() * 9000 + 1000)::int::text;
      end if;
    end;
  end loop;
  return new;
end; $$;
revoke execute on function public.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

